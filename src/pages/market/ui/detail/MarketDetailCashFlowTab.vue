<script setup lang="ts">
import { computed } from 'vue'
import type { MarketCashFlowRow, MarketMetric, MarketPredictionDetail } from '@/entities/market/model/market-detail.types'
import { formatMarketCompact } from '@/entities/market/model/market-detail.adapter'
import { formatMarketPercent } from '@/entities/market/model/market-prediction.adapter'
import { fetchMarketCashFlow } from '@/entities/market/api/market-detail.api'
import { useMarketStatementPeriod } from '@/pages/market/composables/useMarketStatementPeriod'
import MarketStatCard from './MarketStatCard.vue'
import MarketBarChart from './MarketBarChart.vue'
import type { MarketBarChartSeries } from './MarketBarChart.vue'
import MarketInfoHint from './MarketInfoHint.vue'
import MarketButtonGroup from './MarketButtonGroup.vue'
import type { MarketButtonGroupOption } from './MarketButtonGroup.vue'

const props = defineProps<{
  ticker: string
  detail: MarketPredictionDetail
}>()

const annualRows = computed(() => props.detail.cashFlow)
const { period, rows, periodLoading } = useMarketStatementPeriod<MarketCashFlowRow>(
  computed(() => props.ticker),
  annualRows,
  (ticker: string, signal: AbortSignal) => fetchMarketCashFlow(ticker, 'quarterly', signal),
)

const PERIOD_OPTIONS: MarketButtonGroupOption[] = [
  { label: 'Annual', value: 'annual' },
  { label: 'Quarterly', value: 'quarterly' },
]

const chartCategories = computed(() => rows.value.map((r) => r.period))

// Cash Flow Components chart series
const cashFlowComponentsSeries: MarketBarChartSeries[] = [
  { key: 'operating', label: 'Operating', colorVar: '--app-positive' },
  { key: 'investing', label: 'Inversting', colorVar: '--app-primary', negativeColorVar: '--app-negative' },
  { key: 'financing', label: 'Financing', colorVar: '--app-negative' },
]

const cashFlowComponentsData = computed(() =>
  rows.value.map((r) => ({
    operating: r.operatingCashFlow ?? null,
    investing: -(r.investingCashFlow ?? 0),
    financing: r.financingCashFlow ?? null,
  }))
)

// Free Cash Flow Trend chart series
const fcfTrendSeries: MarketBarChartSeries[] = [
  { key: 'freeCashFlow', label: 'Free Cash Flow', colorVar: '--app-accent' },
]

const fcfTrendData = computed(() =>
  rows.value.map((r) => ({
    freeCashFlow: r.freeCashFlow ?? null,
  }))
)

// ---- Helper for formatting values (matches old formatNumber style) ----
function cfValue(value: number | null | undefined): string {
  if (value === null || value === undefined) return '—'
  return formatMarketCompact(value)
}

function cfValueCurrency(value: number | null | undefined): string {
  if (value === null || value === undefined) return '—'
  return formatMarketCompact(value, { currency: true })
}

function cfValuePercent(value: number | null | undefined, signed = false): string {
  if (value === null || value === undefined) return '—'
  return formatMarketPercent(value, signed)
}

// ---- Metric table builder ----
function m(label: string, value: number | null | undefined, format: 'number' | 'currency' = 'number', description = ''): MarketMetric {
  const v = format === 'currency' ? cfValueCurrency(value) : cfValue(value)
  return { label, value: v, description, zero: value === 0 }
}

// ---- Latest row data ----
const latest = computed(() => rows.value.length ? rows.value[rows.value.length - 1] : null)

// ---- Stat cards ----
const operatingCard = computed(() => ({
  title: 'Operating Cash Flow',
  description: `Operating Cash Flow (OCF) refers to the cash generated by a company's core business operations (like selling goods or providing services) minus the cash paid out for those operations. It excludes non-cash items (such as depreciation and amortization) and the impact of investing and financing activities.`,
  value: latest.value ? cfValue(latest.value.operatingCashFlow) : '—',
}))

const freeCashCard = computed(() => ({
  title: 'Free Cash Flow',
  description: `Free Cash Flow (FCF) is calculated as Operating Cash Flow (OCF) minus Capital Expenditures (CapEx). Capital expenditures are investments a company makes to maintain or expand its assets, such as purchasing new equipment or facilities.`,
  value: latest.value ? cfValue(latest.value.freeCashFlow) : '—',
}))

const cashBalCard = computed(() => ({
  title: 'Cash Balance',
  description: `The total amount of cash and cash equivalents a company holds at the end of a specific accounting period.`,
  value: latest.value ? cfValue(latest.value.cashBalance) : '—',
}))

// ---- Activities tables ----
const operatingActivitiesRows = computed((): MarketMetric[] => {
  if (!latest.value) return []
  return [
    m('Net Income', latest.value.netIncome),
    m('Depreciation & Amortization', latest.value.depreciationAndAmortization),
    m('Changes in Working Capital', latest.value.changeInWorkingCapital),
    m('Net Cash From Operations', latest.value.operatingCashFlow, 'currency'),
  ]
})

const investingActivitiesRows = computed((): MarketMetric[] => {
  if (!latest.value) return []
  return [
    m('Capital Expenditure', latest.value.capitalExpenditure),
    m('Acquisitions', latest.value.acquisitionsNet),
    m('Net Cash From Investing', latest.value.investingCashFlow, 'currency'),
  ]
})

const financingActivitiesRows = computed((): MarketMetric[] => {
  if (!latest.value) return []
  return [
    m('Debt Repayment', latest.value.debtRepayment),
    m('Stock Repurchase', latest.value.commonStockRepurchased !== null ? -(latest.value.commonStockRepurchased ?? 0) : null),
    m('Dividends Paid', latest.value.dividendsPaid),
    m('Net Cash From Financing', latest.value.financingCashFlow, 'currency'),
  ]
})

// ---- Summary table (transposed) ----
const summaryRows = computed((): MarketMetric[] => {
  if (!latest.value) return []
  return [
    m('Net Change in Cash', latest.value.netChangeInCash, 'currency'),
    m('Free Cash Flow', latest.value.freeCashFlow, 'currency'),
    m('Ending Cash Balance', latest.value.cashBalance, 'currency'),
  ]
})

// ---- Bottom metric tables ----
const efficiencyMetricsRows = computed((): MarketMetric[] => {
  if (!latest.value) return []
  return [
    { label: 'Gross Operating Cash Flow Ratio', value: cfValue(latest.value.operatingCashFlowRatio), description: 'Operating Cash Flow Ratio is calculated as Operating Cash Flow (OCF) divided by Sales Revenue.', zero: latest.value.operatingCashFlowRatio === 0 },
    { label: 'Cash Flow Yield', value: cfValuePercent(latest.value.cashFlowYield), description: 'Cash Flow Yield is calculated as Free Cash Flow divided by Market Capitalization.', zero: latest.value.cashFlowYield === 0 },
    { label: 'Cash Conversion Cycle', value: cfValue(latest.value.cashConversionCycle), description: 'The Cash Conversion Cycle (CCC) is calculated as Days Sales Outstanding (DSO) + Days Inventory Outstanding (DIO) - Days Payables Outstanding (DPO).', zero: latest.value.cashConversionCycle === 0 },
    { label: 'Operating Cash Flow Growth', value: cfValuePercent(latest.value.operatingCashFlowGrowth), description: 'The Operating Cash Flow Growth Rate is the percentage increase in operating cash flow year-over-year (YoY) or quarter-over-quarter (QoQ).', zero: latest.value.operatingCashFlowGrowth === 0 },
    { label: 'Free Cash Flow Growth', value: cfValuePercent(latest.value.freeCashFlowGrowth), description: 'The Free Cash Flow Growth Rate is the percentage increase in free cash flow year-over-year (YoY) or quarter-over-quarter (QoQ).', zero: latest.value.freeCashFlowGrowth === 0 },
  ]
})

const capitalAllocationRows = computed((): MarketMetric[] => {
  if (!latest.value) return []
  return [
    { label: 'Reinvestment Rate', value: cfValuePercent(latest.value.reinvestmentRate), description: 'The Reinvestment Rate typically refers to the proportion of a company\'s operating cash flow or free cash flow that is used for reinvestment.', zero: latest.value.reinvestmentRate === 0 },
    { label: 'CapEx to Operating Cash', value: cfValuePercent(latest.value.capexToOperatingCash), description: 'Capital Expenditure / Operating Cash Flow is calculated as Capital Expenditures (CapEx) divided by Operating Cash Flow (OCF).', zero: latest.value.capexToOperatingCash === 0 },
    { label: 'Cash Flow Coverage', value: cfValue(latest.value.cashFlowCoverage), description: 'The Cash Flow Coverage Ratio typically refers to Operating Cash Flow (OCF) divided by Total Debt.', zero: latest.value.cashFlowCoverage === 0 },
    { label: 'Cash Conversion Change', value: cfValue(latest.value.cashConversionChange), description: 'This refers to the trend in the Cash Conversion Cycle (CCC) over time.', zero: latest.value.cashConversionChange === 0 },
    { label: 'Operating Ratio Change', value: cfValue(latest.value.operatingRatioChange), description: 'Operating Ratio Change refers to the trend in the Operating Cash Flow Ratio.', zero: latest.value.operatingRatioChange === 0 },
  ]
})

const sustainabilityMetricsRows = computed((): MarketMetric[] => {
  if (!latest.value) return []
  return [
    { label: 'Free Cash Flow Margin', value: cfValuePercent(latest.value.freeCashFlowMargin), description: 'Free Cash Flow Margin is calculated as Free Cash Flow divided by Sales Revenue.', zero: latest.value.freeCashFlowMargin === 0 },
    { label: 'Cash Flow to Debt', value: cfValue(latest.value.freeFlowToDebt), description: 'The Cash Flow/Debt Ratio is calculated as Operating Cash Flow (OCF) divided by Total Debt.', zero: latest.value.freeFlowToDebt === 0 },
  ]
})

// ---- Hide logic ----
// Mirrors Vue2 `CashFlow.vue` `hasZero`: hide the whole block when ANY row is zero.
// `'0.0%'` is included because the Vue3 percent formatter rounds to one decimal
// where Vue2's `formatNumber` produced `'0.00%'`.
function hasZero(rows: MarketMetric[]) {
  if (!Array.isArray(rows)) return false
  return rows.some((r) => ['0.00%', '0.0%', '0.00', '0'].includes(r.value))
}

const hideEfficiency = computed(() => hasZero(efficiencyMetricsRows.value))
const hideCapital = computed(() => hasZero(capitalAllocationRows.value))
const hideSustainability = computed(() => hasZero(sustainabilityMetricsRows.value))
</script>

<template>
  <section class="space-y-3">
    <!-- Period toggle -->
    <MarketButtonGroup
      v-model="period"
      :options="PERIOD_OPTIONS"
      aria-label="Period"
      background-color="var(--app-surface)"
    />

    <!-- 3 stat cards -->
    <div class="grid gap-3 md:grid-cols-3">
      <MarketStatCard
        :title="operatingCard.title"
        :description="operatingCard.description"
        :value="operatingCard.value"
        :loading="periodLoading"
      />
      <MarketStatCard
        :title="freeCashCard.title"
        :description="freeCashCard.description"
        :value="freeCashCard.value"
        :loading="periodLoading"
      />
      <MarketStatCard
        :title="cashBalCard.title"
        :description="cashBalCard.description"
        :value="cashBalCard.value"
        :loading="periodLoading"
      />
    </div>

    <!-- 2 charts -->
    <div class="grid gap-3 xl:grid-cols-2">
      <section class="rounded-lg border border-[var(--app-border)] bg-[var(--app-surface)] p-4">
        <h3 class="mb-3 text-base font-extrabold">Cash Flow Components</h3>
        <MarketBarChart
          :categories="chartCategories"
          :series="cashFlowComponentsSeries"
          :data="cashFlowComponentsData"
          :height="400"
          :loading="periodLoading"
          empty-message="No cash flow data available"
        />
      </section>
      <section class="rounded-lg border border-[var(--app-border)] bg-[var(--app-surface)] p-4">
        <h3 class="mb-3 text-base font-extrabold">Free Cash Flow Trend</h3>
        <MarketBarChart
          :categories="chartCategories"
          :series="fcfTrendSeries"
          :data="fcfTrendData"
          :height="400"
          :loading="periodLoading"
          empty-message="No free cash flow data available"
        />
      </section>
    </div>

    <!-- Cash Flow Activities -->
    <section class="rounded-lg border border-[var(--app-border)] bg-[var(--app-surface)] p-4">
      <h3 class="mb-3 text-lg font-extrabold">Cash Flow Activities</h3>
      <div class="grid gap-3 xl:grid-cols-3">
        <!-- Operating Activities -->
        <div class="rounded-md border border-[var(--app-border-muted)]">
          <h4 class="mb-2 px-3 pt-3 text-sm font-extrabold text-[var(--app-text)]">Operating Activities</h4>
          <div class="divide-y divide-[var(--app-border-muted)]">
            <div
              v-for="(row, index) in operatingActivitiesRows"
              :key="row.label"
              class="flex items-center justify-between px-3 py-2.5 text-sm"
              :class="index === operatingActivitiesRows.length - 1 ? 'bg-[var(--app-surface-muted)]' : ''"
            >
              <span class="inline-flex items-center gap-1.5 font-semibold text-[var(--app-text-secondary)] whitespace-nowrap">
                {{ row.label }}
                <MarketInfoHint v-if="row.description" :text="row.description" />
              </span>
              <span class="font-extrabold whitespace-nowrap text-sm">
                {{ row.value }}
              </span>
            </div>
          </div>
        </div>
        <!-- Investing Activities -->
        <div class="rounded-md border border-[var(--app-border-muted)]">
          <h4 class="mb-2 px-3 pt-3 text-sm font-extrabold text-[var(--app-text)]">Investing Activities</h4>
          <div class="divide-y divide-[var(--app-border-muted)]">
            <div
              v-for="(row, index) in investingActivitiesRows"
              :key="row.label"
              class="flex items-center justify-between px-3 py-2.5 text-sm"
              :class="index === investingActivitiesRows.length - 1 ? 'bg-[var(--app-surface-muted)]' : ''"
            >
              <span class="inline-flex items-center gap-1.5 font-semibold text-[var(--app-text-secondary)] whitespace-nowrap">
                {{ row.label }}
                <MarketInfoHint v-if="row.description" :text="row.description" />
              </span>
              <span class="font-extrabold whitespace-nowrap text-sm">
                {{ row.value }}
              </span>
            </div>
          </div>
        </div>
        <!-- Financing Activities -->
        <div class="rounded-md border border-[var(--app-border-muted)]">
          <h4 class="mb-2 px-3 pt-3 text-sm font-extrabold text-[var(--app-text)]">Financing Activities</h4>
          <div class="divide-y divide-[var(--app-border-muted)]">
            <div
              v-for="(row, index) in financingActivitiesRows"
              :key="row.label"
              class="flex items-center justify-between px-3 py-2.5 text-sm"
              :class="index === financingActivitiesRows.length - 1 ? 'bg-[var(--app-surface-muted)]' : ''"
            >
              <span class="inline-flex items-center gap-1.5 font-semibold text-[var(--app-text-secondary)] whitespace-nowrap">
                {{ row.label }}
                <MarketInfoHint v-if="row.description" :text="row.description" />
              </span>
              <span class="font-extrabold whitespace-nowrap text-sm">
                {{ row.value }}
              </span>
            </div>
          </div>
        </div>
      </div>

      <!-- Summary -->
      <div class="my-4 border-t border-[var(--app-border-muted)]" />
      <div class="rounded-md border border-[var(--app-border-muted)] p-3">
        <h4 class="mb-2 text-sm font-extrabold text-[var(--app-text)]">Summary</h4>
        <div class="flex items-end gap-3 border-b border-[var(--app-border-muted)] pb-2">
          <div
            v-for="row in summaryRows"
            :key="`label-${row.label}`"
            class="flex-1 text-sm font-semibold text-[var(--app-text-secondary)] whitespace-nowrap"
          >
            {{ row.label }}
          </div>
        </div>
        <div class="flex items-center gap-3 pt-2">
          <div
            v-for="row in summaryRows"
            :key="`value-${row.label}`"
            class="flex-1 font-extrabold whitespace-nowrap text-sm"
          >
            {{ row.value }}
          </div>
        </div>
      </div>
    </section>

    <!-- Bottom metrics -->
    <div class="grid gap-3 xl:grid-cols-3">
      <section v-if="!hideEfficiency" class="rounded-lg border border-[var(--app-border)] bg-[var(--app-surface)] p-4">
        <h3 class="mb-3 text-lg font-extrabold">Efficiency Metrics</h3>
        <div class="rounded-md border border-[var(--app-border-muted)]">
          <div class="divide-y divide-[var(--app-border-muted)]">
            <div
              v-for="row in efficiencyMetricsRows"
              :key="row.label"
              class="flex items-center justify-between px-3 py-2.5 text-sm"
            >
              <span class="inline-flex items-center gap-1.5 font-semibold text-[var(--app-text-secondary)] whitespace-nowrap">
                {{ row.label }}
                <MarketInfoHint v-if="row.description" :text="row.description" />
              </span>
              <span class="font-extrabold whitespace-nowrap text-sm">
                {{ row.value }}
              </span>
            </div>
          </div>
        </div>
      </section>
      <section v-if="!hideCapital" class="rounded-lg border border-[var(--app-border)] bg-[var(--app-surface)] p-4">
        <h3 class="mb-3 text-lg font-extrabold">Capital Allocation</h3>
        <div class="rounded-md border border-[var(--app-border-muted)]">
          <div class="divide-y divide-[var(--app-border-muted)]">
            <div
              v-for="row in capitalAllocationRows"
              :key="row.label"
              class="flex items-center justify-between px-3 py-2.5 text-sm"
            >
              <span class="inline-flex items-center gap-1.5 font-semibold text-[var(--app-text-secondary)] whitespace-nowrap">
                {{ row.label }}
                <MarketInfoHint v-if="row.description" :text="row.description" />
              </span>
              <span class="font-extrabold whitespace-nowrap text-sm">
                {{ row.value }}
              </span>
            </div>
          </div>
        </div>
      </section>
      <section v-if="!hideSustainability" class="rounded-lg border border-[var(--app-border)] bg-[var(--app-surface)] p-4">
        <h3 class="mb-3 text-lg font-extrabold">Sustainability Metrics</h3>
        <div class="rounded-md border border-[var(--app-border-muted)]">
          <div class="divide-y divide-[var(--app-border-muted)]">
            <div
              v-for="row in sustainabilityMetricsRows"
              :key="row.label"
              class="flex items-center justify-between px-3 py-2.5 text-sm"
            >
              <span class="inline-flex items-center gap-1.5 font-semibold text-[var(--app-text-secondary)] whitespace-nowrap">
                {{ row.label }}
                <MarketInfoHint v-if="row.description" :text="row.description" />
              </span>
              <span class="font-extrabold whitespace-nowrap text-sm">
                {{ row.value }}
              </span>
            </div>
          </div>
        </div>
      </section>
    </div>
  </section>
</template>
