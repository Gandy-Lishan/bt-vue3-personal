import { CIQ as _CIQ } from "chartiq/js/chartiq.js";
import { getPropertyByString } from "@/utils/globalFunc"


let __js_advanced_studies_fractalChaos_ = (_exports) => {

/* global _CIQ, _timezoneJS, _SplinePlotter */


var CIQ = typeof _CIQ !== "undefined" ? _CIQ : _exports.CIQ;

if (!CIQ.Studies) {
	console.error(
		"fractalChaos feature requires first activating studies feature."
	);
} else {
	CIQ.Studies.calculateFractalChaos = function (stx, sd) {
		var quotes = sd.chart.scrubbed;

		var field	// 它是流动的
		if(sd.parameters.isComparison){
			field = CIQ.store.getters.getComparisonSymbol.url
			if(sd.type == "Fractal Chaos Bands"){
				var actualXaxis = stx.getYAxisByField(stx.panels['chart'], field);
				sd.yAxis = actualXaxis
			}
			quotes = sd.chart.dataSet.filter(item => item.hasOwnProperty(field))
		}else{
			if(sd.type == "Fractal Chaos Bands"){
				sd.yAxis = null
			}
			quotes = sd.chart.scrubbed
		}

		var fractalHigh = 0;
		var fractalLow = 0;
		var test = 0;
		if (sd.startFrom && sd.type == "Fractal Chaos Bands") {
			fractalHigh = quotes[sd.startFrom - 1]["Fractal High " + sd.name];
			fractalLow = quotes[sd.startFrom - 1]["Fractal Low " + sd.name];
		}
		for (var i = Math.max(4, sd.startFrom); i < quotes.length; i++) {
			if (quotes[i].futureTick) break;
			var nHi = !isNaN(getPropertyByString(quotes[i],field,'High')),
				nLo = !isNaN(getPropertyByString(quotes[i],field,'Low'));
			if (nHi || nLo) quotes[i]["Result " + sd.name] = 0;
			var j;
			test = 0;
			for (j = 0; j <= i; j++) {
				if (!quotes[i - j]) break;
				const iminusjHigh = getPropertyByString(quotes[i - j],field,'High')
				const iminus2High = getPropertyByString(quotes[i - 2],field,'High')
				if (iminusjHigh > iminus2High) break;
				if (j < 2 && iminusjHigh == iminus2High) break;
				if (iminusjHigh < iminus2High) test++;
				if (test == 4) {
					fractalHigh = iminus2High;
					break;
				}
			}
			if (sd.type == "Fractal Chaos Bands") {
				if (nHi)
					quotes[i]["Fractal High " + sd.name] =
						fractalHigh > 0 ? fractalHigh : null;
			} else if (test == 4) {
				//oscillator
				quotes[i]["Result " + sd.name] = 1;
			}
			test = 0;
			for (j = 0; j <= i; j++) {
				if (!quotes[i - j]) break;
				const iminusjLow = getPropertyByString(quotes[i - j],field,'Low')
				const iminus2Low = getPropertyByString(quotes[i - 2],field,'Low')
				if (iminusjLow < iminus2Low) break;
				if (j < 2 && iminusjLow == iminus2Low) break;
				if (iminusjLow > iminus2Low) test++;
				if (test == 4) {
					fractalLow = iminus2Low;
					break;
				}
			}
			if (sd.type == "Fractal Chaos Bands") {
				if (nLo)
					quotes[i]["Fractal Low " + sd.name] =
						fractalLow > 0 ? fractalLow : null;
			} else if (test == 4) {
				//oscillator
				quotes[i]["Result " + sd.name] = -1;
			}
		}
	};

	CIQ.Studies.studyLibrary = CIQ.extend(CIQ.Studies.studyLibrary, {
		"Fractal Chaos": {
			name: "Fractal Chaos Oscillator",
			range: "-1 to 1",
			calculateFN: CIQ.Studies.calculateFractalChaos,
			inputs: {},
			centerline: null // so centerline is drawn but not included in the range calculation
		},
		/** 无需处理dual symbol */
		"Fractal Chaos Bands": {
			name: "Fractal Chaos Bands",
			overlay: true,
			calculateFN: CIQ.Studies.calculateFractalChaos,
			seriesFN: CIQ.Studies.displayChannel,
			inputs: { "Channel Fill": true },
			outputs: {
				"Fractal High": "auto",
				"Fractal Low": "auto",
				"Fractal Channel": "auto"
			}
		}
	});
}

};
export {__js_advanced_studies_fractalChaos_}